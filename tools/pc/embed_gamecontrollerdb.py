#!/usr/bin/env python3
"""Embed the controller mappings so every build has them, wherever it runs from.

src/pc/assets/gamecontrollerdb.txt is SDL_GameControllerDB at a pinned commit
(its first lines say which); gamecontrollerdb_extra.txt holds this port's
own lines. Comments and blank lines are left out. The DB's lines are split by
their platform: field, one array per system the port ships, and only the
running system's is compiled in (gamecontrollerdb_platform_txt): sdl.c adds a
line from it only for a controller SDL has no mapping of its own for, line by
line. The port's own lines stay one list; SDL keeps the running system's.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[2]
assets = root / "src/pc/assets"
# The header is included after <SDL3/SDL.h>. SDL defines SDL_PLATFORM_LINUX
# on Android too, so Android is tested first.
PLATFORMS = (
    ("SDL_PLATFORM_ANDROID", "Android"),
    ("SDL_PLATFORM_WINDOWS", "Windows"),
    ("SDL_PLATFORM_MACOS", "Mac OS X"),
    ("SDL_PLATFORM_LINUX", "Linux"),
)


def mappings(path):
    lines = [l for l in path.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    for l in lines:
        if '"' in l or "\\" in l:
            raise SystemExit(f"{path}: a mapping holds a quote or backslash: {l}")
    return lines


def literal(name, lines):
    body = "".join(f'    "{l}\\n"\n' for l in lines) or '    ""\n'
    return f"static const char {name}[] =\n{body};\n"


def platform(line):
    for field in line.split(","):
        if field.startswith("platform:"):
            return field[len("platform:"):]
    return None


db = mappings(assets / "gamecontrollerdb.txt")
extra = mappings(assets / "gamecontrollerdb_extra.txt")
text = "/* Generated by tools/pc/embed_gamecontrollerdb.py. Do not edit. */\n"
counts = []
for i, (macro, name) in enumerate(PLATFORMS):
    lines = [l for l in db if platform(l) == name]
    counts.append(f"{name} {len(lines)}")
    text += f"#{'if' if i == 0 else 'elif'} defined({macro})\n" + literal("gamecontrollerdb_platform_txt", lines)
text += "#else\n" + literal("gamecontrollerdb_platform_txt", []) + "#endif\n"
text += literal("gamecontrollerdb_extra_txt", extra)
out = assets / "gamecontrollerdb_txt.h"
out.write_text(text)
print(f"Embedded SDL_GameControllerDB ({', '.join(counts)}; {len(db)} in all) + {len(extra)} of our own"
      f" into {out.relative_to(root)}")
