#!/usr/bin/env python3
"""Embed the controller mappings so every build has them, wherever it runs from.

src/pc/assets/gamecontrollerdb.txt is SDL_GameControllerDB at a pinned commit
(its first lines say which); gamecontrollerdb_extra.txt holds this port's
own lines. Comments and blank lines are left out; SDL keeps, from each list,
the lines whose platform: field is the running system's.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[2]
assets = root / "src/pc/assets"


def literal(name, path):
    lines = [l for l in path.read_text(encoding="utf-8").splitlines() if l.strip() and not l.startswith("#")]
    for l in lines:
        if '"' in l or "\\" in l:
            raise SystemExit(f"{path}: a mapping holds a quote or backslash: {l}")
    body = "".join(f'    "{l}\\n"\n' for l in lines)
    return f"static const char {name}[] =\n{body};\n", len(lines)


db, db_count = literal("gamecontrollerdb_txt", assets / "gamecontrollerdb.txt")
extra, extra_count = literal("gamecontrollerdb_extra_txt", assets / "gamecontrollerdb_extra.txt")
out = assets / "gamecontrollerdb_txt.h"
out.write_text("/* Generated by tools/pc/embed_gamecontrollerdb.py. Do not edit. */\n" + db + extra)
print(f"Embedded {db_count} + {extra_count} mappings into {out.relative_to(root)}")
